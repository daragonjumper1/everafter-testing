import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const source=path.join(root,'everafter/static'),docs=path.join(root,'docs');
await fs.mkdir(docs,{recursive:true});
for(const name of await fs.readdir(source))if(/\.(js|css)$/.test(name))await fs.copyFile(path.join(source,name),path.join(docs,name));
let html=await fs.readFile(path.join(source,'index.html'),'utf8');
html=html.replaceAll('src="/','src="./').replaceAll('href="/mobile.css"','href="./mobile.css"').replaceAll('href="/planning.css"','href="./planning.css"');
html=html.replace('<script src="./invitation.js"></script>','<script src="./demo-config.js"></script>\n<script src="./checklist-templates.js"></script>\n<script src="./planner-demo.js"></script>\n<script src="./demo-api.js"></script>\n<script src="./invitation.js"></script>');
const apiStart=html.indexOf('async function api(url,'),apiEnd=html.indexOf('\nasync function load()',apiStart);
if(apiStart<0||apiEnd<0)throw Error('Shared API client not found.');
html=html.slice(0,apiStart)+"async function api(url,method='GET',body){return window.everafterDemoApi(url,method,body)}"+html.slice(apiEnd);
const linkStart=html.indexOf('async function copyLink(id){'),linkEnd=html.indexOf('\nfunction assign(',linkStart);
if(linkStart<0||linkEnd<0)throw Error('Shared guest-link function not found.');
html=html.slice(0,linkStart)+"async function copyLink(){toast('Private guest links need the Rust server and are unavailable in this browser-only demo.')}"+html.slice(linkEnd);
const revision=process.env.GITHUB_SHA||'feedback-20261102';
html=html.replace(/(src|href)="(\.\/[^"?]+\.(?:js|css))"/g,(_,attribute,url)=>`${attribute}="${url}?v=${revision}"`);
await fs.writeFile(path.join(docs,'index.html'),html);
let invitation=await fs.readFile(path.join(docs,'invitation.js'),'utf8');
invitation=invitation.replace('function connectInvitationAI(){',"function connectInvitationAI(){toast('AI generation needs the Rust backend. API keys are not accepted in this browser-only demo.');return;");
await fs.writeFile(path.join(docs,'invitation.js'),invitation);
const templates=await fs.readFile(path.join(docs,'checklist-templates.json'),'utf8');
await fs.writeFile(path.join(docs,'checklist-templates.js'),'window.EVERAFTER_STARTERS='+templates+';\n');
console.log('Built browser-only testing demo from shared application source.');
